semantic_model = SentenceTransformer('all-MiniLM-L6-v2')

def calculate_perplexity(text):
    gpt_model.eval()
    inputs = gpt_tokenizer(text, return_tensors="pt", truncation=True, max_length=256).to(device)
    with torch.no_grad():
        outputs = gpt_model(**inputs, labels=inputs["input_ids"])
    return round(math.exp(min(outputs.loss.item(), 20)), 2)

def calculate_bleu(reference, hypothesis):
    smoother = SmoothingFunction().method1
    return round(sentence_bleu([reference.split()], hypothesis.split(), smoothing_function=smoother), 4)

def calculate_semantic_similarity(t1, t2):
    e1 = semantic_model.encode(t1, convert_to_tensor=True)
    e2 = semantic_model.encode(t2, convert_to_tensor=True)
    return round(util.cos_sim(e1, e2).item(), 4)

_EVAL_STOPWORDS = {"recent","advances","suggest","studies","show","indicate",
                    "has","have","the","of","in","and","a","an","that","for",
                    "been","which","with","from","this","these","their","role",
                    "approaches","applications","treatments","based","novel",
                    "early","detection","disorders"}

def _extract_keywords(prompt, k=4):
    words = [w.strip(".,;:").lower() for w in prompt.split()]
    words = [w for w in words if w not in _EVAL_STOPWORDS and len(w) > 3]
    return words[:k]

def find_topical_reference(prompt, corpus, fallback_idx=0):
    """Return the chunk in `corpus` with the most keyword hits for `prompt`'s topic.
    Falls back to the first chunk if nothing matches (should be rare)."""
    keywords = _extract_keywords(prompt)
    if not keywords:
        return corpus[fallback_idx]

    best_idx, best_hits = None, 0
    for idx, chunk in enumerate(corpus):
        chunk_lower = chunk.lower()
        hits = sum(1 for kw in keywords if kw in chunk_lower)
        if hits > best_hits:
            best_hits, best_idx = hits, idx
            if best_hits == len(keywords):
                break
    return corpus[best_idx] if best_idx is not None else corpus[fallback_idx]
