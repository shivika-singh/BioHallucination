def create_adversarial_example(text):
    """Corrupt real text by swapping medical terms — creates hard negatives."""
    words = text.split()
    num_swaps = max(1, len(words) // 30)
    swapped = 0

    for i, word in enumerate(words):
        word_lower = word.lower().rstrip('.,;:')
        if word_lower in MEDICAL_SUBSTITUTIONS and swapped < num_swaps:
            replacement = random.choice(MEDICAL_SUBSTITUTIONS[word_lower])
            words[i] = replacement
            swapped += 1


    for i, word in enumerate(words):
        if word.replace('.','').replace('%','').isdigit() and random.random() < 0.3:
            try:
                num = float(word.replace('%',''))
                words[i] = str(round(num * random.uniform(0.5, 2.0), 1))
            except:
                pass

    return " ".join(words)


