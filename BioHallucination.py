def detect_hallucination(text, temperature=best_temp):
    """Calibrated hallucination detection with temperature scaling."""
    disc_model.eval()
    inputs = bert_tokenizer(
        text, return_tensors="pt", truncation=True,
        padding=True, max_length=256
    ).to(device)
    with torch.no_grad():
        outputs = disc_model(**inputs)
    scaled_logits = outputs.logits / temperature
    probs         = torch.softmax(scaled_logits, dim=1)
    real_score    = round(probs[0][1].item(), 4)
    hall_score    = round(probs[0][0].item(), 4)
    return real_score, hall_score

def detect_sentence_level(text, temperature=best_temp):
    """Score each sentence individually."""
    sentences = sent_tokenize(text)
    results   = []
    for sent in sentences:
        if len(sent.split()) < 5:
            continue
        r, h = detect_hallucination(sent, temperature)
        label = "HIGH" if h > 0.6 else ("MODERATE" if h > 0.35 else "LOW")
        results.append({"sentence": sent, "real": r, "risk": h, "label": label})
    return results

