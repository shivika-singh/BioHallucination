def fetch_pubmed_abstracts(query, max_results=3):
    """Fetch real verified PubMed abstracts via NCBI Entrez API."""
    try:
        handle  = Entrez.esearch(db="pubmed", term=query, retmax=max_results, sort="relevance")
        record  = Entrez.read(handle)
        ids     = record["IdList"]
        if not ids:
            return ["No PubMed results found for this query."]
        handle  = Entrez.efetch(db="pubmed", id=",".join(ids), rettype="abstract", retmode="text")
        raw     = handle.read()
        abstracts = [a.strip() for a in raw.split("\n\n") if len(a.strip()) > 100]
        return abstracts[:max_results]
    except Exception as e:
        return [f"PubMed retrieval error: {str(e)}"]

def extract_topic(prompt):
    stopwords = {"recent","advances","suggest","studies","show","indicate",
                 "has","have","the","of","in","and","a","an","that","for",
                 "been","which","with","from","this","these","their"}
    words = [w for w in prompt.lower().split() if w not in stopwords and len(w) > 3]
    return " ".join(words[:5])


